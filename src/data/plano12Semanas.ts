/* =============================================================================
 * Plano periodizado de 90 dias (12 semanas, 3 mesociclos) para o MÉDICO GENERALISTA
 * que presta concursos periciais (Perito Médico Federal/INSS, peritos de RPPS,
 * Perito Médico-Legista) e, como porta de entrada, editais de Clínico Geral/ESF.
 *
 * Cada semana do plano tem 7 dias relativos à data de início:
 *   dias 1–5 → teoria + lei seca + questões
 *   dia 6    → bateria por banca / simulado (blocos `sabado`)
 *   dia 7    → revisões espaçadas devidas + caderno de erros (gerado pelo agendador)
 *
 * Trilhas padrão por eixo:
 *   pericia → Generalista + Perícia · legal → Generalista + Legista
 *   clinica → Generalista + Clínico + Perícia (o edital de Perito Médico Federal cobra
 *             "Medicina Geral": clínica, GO, psiquiatria, ortopedia, cardio, pneumo,
 *             endócrino, epidemiologia e PNI)
 *   tronco  → todas
 * Blocos de aprofundamento são exclusivos da trilha focada (SO_PER, SO_LEG, SO_CLIN).
 * ========================================================================== */

const GEN_PER: Trilha[] = ['generalista', 'pericia'];
const GEN_LEG: Trilha[] = ['generalista', 'legista'];
const CLIN_PER: Trilha[] = ['generalista', 'clinico', 'pericia'];
const SO_PER: Trilha[] = ['pericia'];
const SO_LEG: Trilha[] = ['legista'];
const SO_CLIN: Trilha[] = ['clinico'];
const TODAS: Trilha[] = [...TRILHAS];

type BlocoDraft = Omit<BlocoSemana, 'id' | 'semana'>;

interface Opts {
  trilhas?: Trilha[];
  essencial?: boolean;
  plantao?: string;
  sabado?: boolean;
  refs?: string[];
}

function trilhasPadrao(eixo: Eixo): Trilha[] {
  if (eixo === 'pericia') return GEN_PER;
  if (eixo === 'legal') return GEN_LEG;
  if (eixo === 'clinica') return CLIN_PER;
  return TODAS;
}

function b(
  eixo: Eixo,
  tipo: TipoBloco,
  minutos: number,
  titulo: string,
  descricao: string,
  temaIds: string[],
  opts: Opts = {},
): BlocoDraft {
  const primeiro = getTema(temaIds[0] ?? '');
  if (!primeiro) throw new Error(`Tema inexistente no bloco "${titulo}": ${temaIds[0]}`);
  const trilhas = opts.trilhas ?? trilhasPadrao(eixo);
  const aprofundamento = trilhas.length === 1;
  const essencialPadrao = !aprofundamento && ['teoria', 'lei-seca', 'diagnostico', 'simulado'].includes(tipo);
  let plantao = opts.plantao;
  if (!plantao && tipo === 'questoes') plantao = `15 questões rápidas: ${primeiro.tema.nome} (filtro da semana).`;
  if (!plantao && tipo === 'lei-seca') plantao = `15 min de leitura dos itens ainda não marcados no checklist de ${primeiro.tema.nome}.`;
  const refs = opts.refs ?? primeiro.tema.refs;
  return {
    eixo,
    disciplinaId: primeiro.disciplina.id,
    temaIds,
    tipo,
    titulo,
    descricao,
    minutos,
    essencial: opts.essencial ?? essencialPadrao,
    trilhas,
    ...(plantao ? { plantaoAlternativa: plantao } : {}),
    ...(opts.sabado ? { sabado: true } : {}),
    ...(refs && refs.length ? { refs } : {}),
  };
}

function semana(
  n: number,
  mesociclo: Mesociclo,
  titulo: string,
  objetivo: string,
  bancasFoco: string[],
  metaQuestoes: number,
  blocos: BlocoDraft[],
): SemanaPlano {
  const nn = String(n).padStart(2, '0');
  return {
    semana: n,
    mesociclo,
    titulo,
    objetivo,
    bancasFoco,
    metaQuestoes,
    blocos: blocos.map((bl, i) => ({ ...bl, id: `s${nn}-b${String(i + 1).padStart(2, '0')}`, semana: n })),
  };
}

