/* =============================================================================
 * Plano periodizado de 90 dias (12 semanas, 3 mesociclos).
 * Cada semana do plano tem 7 dias relativos à data de início:
 *   dias 1–5 → teoria + lei seca + questões
 *   dia 6    → bateria por banca / simulado (blocos `sabado`)
 *   dia 7    → revisões espaçadas devidas + caderno de erros (gerado pelo agendador)
 * Trilhas padrão por eixo:
 *   trabalho → Híbrida + Só Trabalho · legal → Híbrida + Só Legista · tronco → todas
 *   blocos de aprofundamento são exclusivos da trilha focada; clínica → só Municipal.
 * ========================================================================== */

const T_TRAB: Trilha[] = ['hibrida', 'trabalho'];
const T_LEG: Trilha[] = ['hibrida', 'legista'];
const SO_TRAB: Trilha[] = ['trabalho'];
const SO_LEG: Trilha[] = ['legista'];
const MUN: Trilha[] = ['municipal'];
const TODAS: Trilha[] = [...TRILHAS];

type BlocoDraft = Omit<BlocoSemana, 'id' | 'semana'>;

interface Opts {
  trilhas?: Trilha[];
  essencial?: boolean;
  plantao?: string;
  sabado?: boolean;
  refs?: string[];
}

function trilhasPadrao(eixo: Eixo, temaIds: string[]): Trilha[] {
  if (eixo === 'trabalho') return T_TRAB;
  if (eixo === 'legal') return T_LEG;
  // Tronco: clínica médica só interessa à trilha municipal.
  const clinica = temaIds.some((t) => t.startsWith('cm-'));
  return clinica ? MUN : TODAS;
}

function b(
  eixo: Eixo,
  tipo: TipoBloco,
  minutos: number,
  titulo: string,
  descricao: string,
  temaIds: string[],
  opts: Opts = {},
): BlocoDraft {
  const primeiro = getTema(temaIds[0] ?? '');
  if (!primeiro) throw new Error(`Tema inexistente no bloco "${titulo}": ${temaIds[0]}`);
  const trilhas = opts.trilhas ?? trilhasPadrao(eixo, temaIds);
  const aprofundamento = trilhas.length === 1 && (trilhas[0] === 'trabalho' || trilhas[0] === 'legista');
  const essencialPadrao = !aprofundamento && ['teoria', 'lei-seca', 'diagnostico', 'simulado'].includes(tipo);
  let plantao = opts.plantao;
  if (!plantao && tipo === 'questoes') plantao = `15 questões rápidas: ${primeiro.tema.nome} (filtro da semana).`;
  if (!plantao && tipo === 'lei-seca') plantao = `15 min de leitura dos itens ainda não marcados no checklist de ${primeiro.tema.nome}.`;
  const refs = opts.refs ?? primeiro.tema.refs;
  return {
    eixo,
    disciplinaId: primeiro.disciplina.id,
    temaIds,
    tipo,
    titulo,
    descricao,
    minutos,
    essencial: opts.essencial ?? essencialPadrao,
    trilhas,
    ...(plantao ? { plantaoAlternativa: plantao } : {}),
    ...(opts.sabado ? { sabado: true } : {}),
    ...(refs && refs.length ? { refs } : {}),
  };
}

function semana(
  n: number,
  mesociclo: Mesociclo,
  titulo: string,
  objetivo: string,
  bancasFoco: string[],
  metaQuestoes: number,
  blocos: BlocoDraft[],
): SemanaPlano {
  const nn = String(n).padStart(2, '0');
  return {
    semana: n,
    mesociclo,
    titulo,
    objetivo,
    bancasFoco,
    metaQuestoes,
    blocos: blocos.map((bl, i) => ({ ...bl, id: `s${nn}-b${String(i + 1).padStart(2, '0')}`, semana: n })),
  };
}

